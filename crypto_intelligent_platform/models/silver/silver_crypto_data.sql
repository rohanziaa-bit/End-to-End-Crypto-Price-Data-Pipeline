SELECT
  COIN_ID AS COIN_ID,
  TRIM(COIN_NAME) AS COIN_NAME,
  TRIM(SYMBOL) AS SYMBOL,
  CAST(ROUND(PRICE_USD, 2) AS DECIMAL(10,2)) AS PRICE_USD,
  CAST(ROUND(LOW_24H_USD,2) AS DECIMAL(10,2)) AS LOW_24_HOUR_USD,
  CAST(ROUND(HIGH_24H_USD,2) AS DECIMAL(10,2)) AS HIGH_24_HOUR_USD,
  MARKET_CAP_USD,
  CAST(ROUND(PRICE_CHANGE_24H_PCT,2) AS DECIMAL(10,2)) AS PRICE_CHANGE_24H_PCT,
  CASE
     WHEN PRICE_CHANGE_24H_PCT > 0 THEN 'POSITIVE'
     WHEN PRICE_CHANGE_24H_PCT < 0 THEN 'NEGATIVE'
  END AS PRICE_MOMENT,
  LAST_UPDATED,
  INGESTED_AT
FROM {{ ref('bronze_crypto_data')}}
WHERE COIN_ID IS NOT NULL
