CREATE TABLE IF NOT EXISTS CRYPTO_PRICES (
    COIN_ID VARCHAR(100),
    SYMBOL VARCHAR(20),
    COIN_NAME VARCHAR(100),
    PRICE_USD NUMBER(38,8),
    MARKET_CAP_USD NUMBER(38,2),
    VOLUME_24H_USD NUMBER(38,2),
    HIGH_24H_USD NUMBER(38,8),
    LOW_24H_USD NUMBER(38,8),
    PRICE_CHANGE_24H_PCT FLOAT,
    LAST_UPDATED VARCHAR(50),
    INGESTED_AT VARCHAR(50)
);

