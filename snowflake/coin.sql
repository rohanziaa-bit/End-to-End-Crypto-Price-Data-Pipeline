SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT COIN_ID) AS UNIQUE_COINS,
    COUNT(DISTINCT INGESTED_AT) AS UNIQUE_INGESTION_TIMES,
    MIN(INGESTED_AT) AS FIRST_INGESTION,
    MAX(INGESTED_AT) AS LAST_INGESTION
FROM CRYPTO_DB.RAW.CRYPTO_PRICES;
SELECT
    COIN_ID,
    SYMBOL,
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT INGESTED_AT) AS SNAPSHOTS,
    MIN(INGESTED_AT) AS FIRST_INGESTION,
    MAX(INGESTED_AT) AS LAST_INGESTION
FROM CRYPTO_DB.RAW.CRYPTO_PRICES
GROUP BY COIN_ID, SYMBOL
ORDER BY SYMBOL;

